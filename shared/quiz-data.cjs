const dayKey = (ms) => new Date(ms + 8 * 3600e3).toISOString().slice(0, 10);
const dayNum = (ms) => Math.floor((ms + 8 * 3600e3) / 86400e3);
const hash = (s) => { let h = 2166136261; for (const c of String(s)) { h ^= c.charCodeAt(0); h = Math.imul(h, 16777619); } return h >>> 0; };
// 今天的題目:題庫輪流出,每輪的順序都用輪數洗牌,避免固定規律
function today(now) {
  const n = Q.length, dn = dayNum(now), round = Math.floor(dn / n), pos = dn % n;
  const order = Q.map((_, i) => i).sort((a, b) => hash(round + "|" + a) - hash(round + "|" + b));
  const idx = order[pos], q = Q[idx];
  const opts = q[1].map((t, i) => ({ t, ok: i === 0 })).sort((a, b) => hash(dayKey(now) + "|" + a.t) - hash(dayKey(now) + "|" + b.t));
  return { day: dayKey(now), q: q[0], opts: opts.map((o) => o.t), ans: opts.findIndex((o) => o.ok), exp: q[2] };
}
